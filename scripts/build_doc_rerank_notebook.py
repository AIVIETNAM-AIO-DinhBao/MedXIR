"""Generate src/notebooks/kaggle_doc_rerank.ipynb: rerank candidate documents, rebuild the nb60 submission.

Document recall (0.47) is the ceiling of every hybrid submission, and the metric is set-based: a document
reranker only helps by changing which documents make the cut at 200. So every candidate document around
the cut is scored: the submitted 200 (top3 of chunk scores), then the other pool documents, best chunk
first, within the rank zone DOC_RERANKERS[name] per query. A document is shown as its lead (first LEAD_CHARS
characters of the text, the title for most pages) + its DOC_CHUNKS best pool chunks.

Scores go to doc_rank.parquet (one column per reranker), then expand_chunks.build_variants() writes the
nb60 chunk lists with the document lists fused by RRF (variants 'nb60-drr-*'), so the result compares to
nb60 (FINAL 0.2235) with only the documents changed.

RTX Pro 6000, Internet OFF. Inputs: kernel outputs medxir-chunk-corpus, medxir-package-rerankers; the
hybrid run's pool.parquet + medxir-hybrid-submission (dataset medxir-output/full-config).

    uv run python scripts/build_doc_rerank_notebook.py
"""
