def read_chunking():
    """scripts/chunking.py up to its __main__ guard, verbatim."""
    source = CHUNKING.read_text(encoding='utf-8')
    if source.count(GUARD) != 1:
        raise ValueError('expected exactly one __main__ guard in scripts/chunking.py')
    return source.split(GUARD)[0].rstrip() + '\n'


def build(prefix, parts, chunking=None):
    cells = []
    for i, (kind, text) in enumerate(parts):
        cell_id = f'{prefix}-{i:02d}'
        if kind == 'md':
            cells.append(new_markdown_cell(text.strip('\n') + '\n', id=cell_id))
        else:
            source = chunking if text == 'CHUNKING_SOURCE' else text.strip('\n') + '\n'
            cells.append(new_code_cell(source, id=cell_id))
    notebook = new_notebook(cells=cells)
    notebook.metadata = {'kernelspec': {'name': 'python3', 'display_name': 'Python 3', 'language': 'python'},
                         'language_info': {'name': 'python'}}
    validate(notebook)
    return notebook


def main():
    NOTEBOOKS.mkdir(exist_ok=True)
    chunking = read_chunking()
    for path, parts, prefix in [
        (NOTEBOOKS / 'kaggle_embed_benchmark.ipynb', BENCHMARK, 'bench'),
        (NOTEBOOKS / 'kaggle_package_models.ipynb', PACKAGE, 'pack'),
    ]:
        write(build(prefix, parts, chunking), str(path))
        print('wrote', path)


if __name__ == '__main__':
    main()
