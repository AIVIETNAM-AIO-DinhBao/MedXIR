"""Generate the Kaggle notebook that writes LLM query variants and encodes them with both 8B embedders.

  src/notebooks/kaggle_query_variants.ipynb

One RTX Pro 6000 session (Internet OFF), three packaged models attached through kernel_sources:
  1. Qwen3-8B (thinking off, greedy) answers each of the 1,200 queries with one JSON object:
       question  the query rewritten as one clean Vietnamese question (spelling, accents, no narrative)
       terms     3-8 medical terms: stated or most likely disease (with the English name or abbreviation),
                 active ingredients, tests, organs
       passage   an 80-120 word answer in the style of a Vietnamese hospital health article (HyDE)
     A row whose output does not parse falls back to the original query for every field.
  2. Octen-Embedding-8B and Qwen3-Embedding-8B encode question and terms as queries (with the instruction)
     and passage as a document (no instruction; Octen's one-space document prefix), so the passage is
     compared with chunks the way chunks were embedded.

Outputs: variants.parquet (id, question, terms, passage, raw, parsed), vectors-<model>-<field>.npy (1200 x 4096,
float32, L2-normalised, query order), query_ids.json.

    uv run python scripts/build_variants_notebook.py
"""
