"""Generate src/notebooks/kaggle_embed_icd_octen8b.ipynb: embed the ICD-10 chapter descriptions with Octen-Embedding-8B.

The 22 chapters x 3 languages from configs/icd10_chapters.json are written into the notebook, so no dataset is
needed. Embedding reuses the GPU check, model load and embed cells of the corpus notebook (same prefix, pooling,
max length), so the vectors share the space of the stored chunk vectors.

Output (/kaggle/working): icd_vectors.npy (66 x 4096 float16, rows in icd_rows.json order), icd_rows.json

    uv run python scripts/build_icd_notebook.py
"""
import json
from pathlib import Path

import build_embed_corpus_notebook as corpus

ROOT = Path(__file__).resolve().parent.parent

INTRO = """
# Embed the ICD-10 chapter descriptions with Octen-Embedding-8B

Generated by `scripts/build_icd_notebook.py`. Edit the generator, not this file.

Run on RTX Pro 6000 with Internet OFF. Attach `boinhbo/medxir-package-octen8b`.
"""

PARAMS = """
import glob
import json
import os
import time

MODEL = 'Octen/Octen-Embedding-8B'
MODEL_DIR = 'Octen-Embedding-8B'
DOC_PREFIX = ' '   # Octen's document prompt, as in the corpus embedding
EXPECT_GPU = '6000'
BATCH = 16
MAX_LENGTH = 1024
OUT = '/kaggle/working'
ROWS = @ROWS@
"""

RUN = """
vectors, tokens = embed_texts([DOC_PREFIX + row['text'] for row in ROWS])
assert vectors.shape == (len(ROWS), 4096) and np.isfinite(vectors.astype(np.float32)).all()
np.save(f'{OUT}/icd_vectors.npy', vectors)
with open(f'{OUT}/icd_rows.json', 'w', encoding='utf-8') as file:
    json.dump([{k: row[k] for k in ('id', 'lang')} for row in ROWS], file, ensure_ascii=False)
print('embedded', len(ROWS), 'texts,', tokens, 'tokens')
"""


def main():
    chapters = json.loads((ROOT / 'configs' / 'icd10_chapters.json').read_text(encoding='utf-8'))['chapters']
    rows = [dict(id=c['id'], lang=lang, text=c[lang]) for c in chapters for lang in ('vi', 'en', 'zh')]
    cells = [
        ('md', INTRO),
        ('code', PARAMS.replace('@ROWS@', json.dumps(rows, ensure_ascii=False, indent=1))),
        ('code', corpus.CODE_ENV),
        ('code', corpus.CODE_LOAD),
        ('code', corpus.CODE_EMBED),
        ('code', RUN),
    ]
    output = ROOT / 'src' / 'notebooks' / 'kaggle_embed_icd_octen8b.ipynb'
    output.write_text(json.dumps(corpus.notebook(cells), ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(f'{output}: {len(cells)} cells, {len(rows)} texts')


if __name__ == '__main__':
    main()
